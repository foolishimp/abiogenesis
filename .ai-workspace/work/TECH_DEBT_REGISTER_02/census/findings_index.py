#!/usr/bin/env python3
"""One line per candidate entry across the area findings files.

Usage: python3 findings_index.py <findingsDir> > INDEX.md
"""
import os, re, sys

d = sys.argv[1]
FIELDS = ["Category", "Retire", "Size", "Risk", "Change class", "Confidence"]


def clip(s, n):
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[: n - 1] + "…"


print("# Index of candidate entries\n")
print("Generated by `census/findings_index.py`. One row per `###` entry that carries a Category line.\n")
total = 0
for name in sorted(os.listdir(d)):
    if not name.endswith(".md") or name in ("INDEX.md", "executive-notes.md"):
        continue
    text = open(os.path.join(d, name), encoding="utf-8").read()
    parts = re.split(r"^### +", text, flags=re.M)[1:]
    rows = []
    for part in parts:
        title, _, body = part.partition("\n")
        body = re.split(r"^## +", body, flags=re.M)[0]
        got = {}
        for f in FIELDS:
            m = re.search(r"^[-*] \**%s\**:\**\s*(.*(?:\n(?![-*] \**[A-Z][A-Za-z ]+\**:)(?!\s*$).*)*)" % re.escape(f), body, flags=re.M)
            if m:
                got[f] = m.group(1)
        if "Category" not in got:
            continue
        rows.append((title.strip(), got, body.count("\n")))
    area = name[:-3]
    print(f"## {area} ({len(rows)} entries)\n")
    print("| Entry | Category | Size | Risk | Class | Confidence | Retire |")
    print("|---|---|---|---|---|---|---|")
    for title, g, n in rows:
        print("| %s | %s | %s | %s | %s | %s | %s |" % (
            clip(title, 110), clip(g.get("Category", ""), 34), clip(g.get("Size", ""), 44), clip(g.get("Risk", ""), 60),
            clip(g.get("Change class", ""), 22), clip(g.get("Confidence", ""), 30), clip(g.get("Retire", ""), 200)))
    print()
    total += len(rows)
print(f"Total: {total} candidate entries.")
